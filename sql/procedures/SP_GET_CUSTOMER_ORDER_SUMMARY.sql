CREATE OR REPLACE PROCEDURE SP_GET_CUSTOMER_ORDER_SUMMARY()
RETURNS TABLE
(
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR(100),
    TOTAL_ORDERS NUMBER,
    TOTAL_ORDER_AMOUNT NUMBER(38,2),
    COMPLETED_ORDERS NUMBER,
    PENDING_ORDERS NUMBER
)
LANGUAGE SQL
AS
$$
DECLARE
    RES RESULTSET;

BEGIN

    RES := (
        SELECT
            C.CUSTOMER_ID,
            C.CUSTOMER_NAME,
            COUNT(O.ORDER_ID) AS TOTAL_ORDERS,
            COALESCE(SUM(O.ORDER_AMOUNT), 0) AS TOTAL_ORDER_AMOUNT,

            COALESCE(
                SUM(IFF(O.ORDER_STATUS = 'COMPLETED', 1, 0)), 0
            ) AS COMPLETED_ORDERS,

            COALESCE(
                SUM(IFF(O.ORDER_STATUS = 'PENDING', 1, 0)), 0
            ) AS PENDING_ORDERS

        FROM CUSTOMERS C

        LEFT JOIN ORDERS O
            ON C.CUSTOMER_ID = O.CUSTOMER_ID

        GROUP BY
            C.CUSTOMER_ID,
            C.CUSTOMER_NAME

        ORDER BY C.CUSTOMER_ID
    );

    RETURN TABLE(RES);

END;
$$;